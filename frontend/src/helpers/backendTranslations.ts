export function translateBackendField(value: string | null | undefined, fallback = 'Не указано') {
  if (!value) return fallback
  return backendFieldTranslations[value] ?? value.replaceAll('_', ' ')
}

const translatableBackendTokens = /\b(train_chief|ptb|police|medic|ambulance)\b/gi

export function translateBackendText(value: string) {
  return value.replace(translatableBackendTokens, (token) => backendFieldTranslations[token.toLowerCase()] ?? token)
}
